class _CompiledPattern {
  _CompiledPattern(this.regex, this.parts);
  final RegExp regex;
  final List<String> parts; // English template split on `{}`
}

List<_CompiledPattern>? _compiled;

List<_CompiledPattern> _patterns() {
  final cached = _compiled;
  if (cached != null) return cached;
  final list = <_CompiledPattern>[];
  kSwToEnPatterns.forEach((sw, en) {
    final fixed = sw.replaceAll('{}', '');
    // A pattern made only of punctuation/placeholders would match anything.
    if (RegExp(r'[A-Za-z]{3}').allMatches(fixed).isEmpty) return;
    final pieces = sw.split('{}').map(RegExp.escape).toList();
    final regex = RegExp('^${pieces.join('(.+?)')}\$', dotAll: true);
    list.add(_CompiledPattern(regex, en.split('{}')));
  });
  _compiled = list;
  return list;
}

const Map<String, String> _months = {
  'januari': 'January', 'februari': 'February', 'machi': 'March', 'aprili': 'April',
  'mei': 'May', 'juni': 'June', 'julai': 'July', 'agosti': 'August',
  'septemba': 'September', 'oktoba': 'October', 'novemba': 'November', 'desemba': 'December',
};

final RegExp _monthRegex = RegExp(
  r'\b(januari|februari|machi|aprili|mei|juni|julai|agosti|septemba|oktoba|novemba|desemba)\b',
  caseSensitive: false,
);

String _translateMonths(String s) {
  return s.replaceAllMapped(_monthRegex, (m) {
    final word = m.group(0)!;
    final en = _months[word.toLowerCase()]!;
    if (word == word.toUpperCase()) return en.toUpperCase();
    return en;
  });
}

const List<String> _separators = [' - ', ' • ', ' | ', ': ', ' / '];

String _translate(String s, int depth) {
  if (s.isEmpty || depth > 4) return s;
  final exact = kSwToEn[s];
  if (exact != null) return exact;

  // Keep surrounding whitespace (e.g. 'Mfanyakazi: ' with a trailing space).
  final trimmed = s.trim();
  if (trimmed.isNotEmpty && trimmed != s) {
    final hit = kSwToEn[trimmed];
    if (hit != null) {
      final start = s.indexOf(trimmed);
      return s.substring(0, start) + hit + s.substring(start + trimmed.length);
    }
  }

  for (final p in _patterns()) {
    final m = p.regex.firstMatch(s);
    if (m == null) continue;
    final b = StringBuffer(p.parts.first);
    for (var i = 0; i < p.parts.length - 1; i++) {
      b.write(_translate(m.group(i + 1)!, depth + 1));
      b.write(p.parts[i + 1]);
    }
    return b.toString();
  }

  // Composite strings like "Title - JANUARI 2026" or "ID • Cheo": translate each segment.
  for (final sep in _separators) {
    if (!s.contains(sep)) continue;
    final segments = s.split(sep);
    final translated = segments.map((e) => _translate(e, depth + 1)).toList();
    var changed = false;
    for (var i = 0; i < segments.length; i++) {
      if (segments[i] != translated[i]) changed = true;
    }
    if (changed) return translated.join(sep);
  }

  final withMonths = _translateMonths(s);
  return withMonths;
}

/// Translates a Swahili UI string to English. Unknown strings are returned
/// unchanged (so a missing translation never breaks the screen).
String translateText(String s) => _translate(s, 0);

/// Translates [s] only when the app is currently in English.
String tr(String s) => appIsEnglish ? translateText(s) : s;
